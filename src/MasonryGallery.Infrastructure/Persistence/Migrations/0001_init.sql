CREATE TABLE IF NOT EXISTS Library (
  Id INTEGER PRIMARY KEY,
  Name TEXT NOT NULL,
  RootPath TEXT NOT NULL UNIQUE,
  Enabled INTEGER NOT NULL DEFAULT 1,
  Status INTEGER NOT NULL DEFAULT 0,
  FollowSymlinks INTEGER NOT NULL DEFAULT 0,
  LastScanId INTEGER NOT NULL DEFAULT 0,
  LastScanUtc INTEGER
);

CREATE TABLE IF NOT EXISTS Media (
  Id INTEGER PRIMARY KEY AUTOINCREMENT,
  LibraryId INTEGER NOT NULL REFERENCES Library(Id) ON DELETE CASCADE,
  RelPath TEXT NOT NULL,
  FileName TEXT NOT NULL,
  Kind INTEGER NOT NULL,
  SizeBytes INTEGER NOT NULL,
  ModifiedUtc INTEGER NOT NULL,
  DateTaken INTEGER,
  DateAdded INTEGER NOT NULL,
  Width INTEGER,
  Height INTEGER,
  DurationMs INTEGER,
  Placeholder BLOB,
  ProbeState INTEGER NOT NULL DEFAULT 0,
  ThumbState INTEGER NOT NULL DEFAULT 0,
  ThumbVersion INTEGER NOT NULL DEFAULT 0,
  ErrorCode INTEGER,
  QuickHash INTEGER,
  ScanId INTEGER NOT NULL,
  DeletedAt INTEGER,
  Favorite INTEGER NOT NULL DEFAULT 0,
  UNIQUE (LibraryId, RelPath)
);

CREATE INDEX IF NOT EXISTS IX_Media_Sort_Taken ON Media (DateTaken DESC, Id DESC) WHERE DeletedAt IS NULL;
CREATE INDEX IF NOT EXISTS IX_Media_Library_Taken ON Media (LibraryId, DateTaken DESC, Id DESC) WHERE DeletedAt IS NULL;
CREATE INDEX IF NOT EXISTS IX_Media_Kind_Taken ON Media (Kind, DateTaken DESC, Id DESC) WHERE DeletedAt IS NULL;
CREATE INDEX IF NOT EXISTS IX_Media_Pending ON Media (ThumbState) WHERE ThumbState = 0;
CREATE INDEX IF NOT EXISTS IX_Media_Quick ON Media (QuickHash) WHERE QuickHash IS NOT NULL;

CREATE TABLE IF NOT EXISTS Tag (Id INTEGER PRIMARY KEY, Name TEXT NOT NULL UNIQUE COLLATE NOCASE);
CREATE TABLE IF NOT EXISTS MediaTag (
  MediaId INTEGER NOT NULL REFERENCES Media(Id) ON DELETE CASCADE,
  TagId INTEGER NOT NULL REFERENCES Tag(Id) ON DELETE CASCADE,
  PRIMARY KEY (MediaId, TagId)
) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS IX_MediaTag_Tag ON MediaTag (TagId, MediaId);

CREATE VIRTUAL TABLE IF NOT EXISTS MediaFts USING fts5(FileName, RelPath, content='Media', content_rowid='Id', tokenize='unicode61 remove_diacritics 2');

CREATE TABLE IF NOT EXISTS SchemaVersion (Version INTEGER NOT NULL);
